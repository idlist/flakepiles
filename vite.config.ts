import vue from '@vitejs/plugin-vue'
import { builtinModules } from 'node:module'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vite'
import banner from 'vite-plugin-banner'
import { type Target, viteStaticCopy as copy } from 'vite-plugin-static-copy'

const external: string[] = [
  'obsidian',
  'electron',
  '@codemirror/autocomplete',
  '@codemirror/collab',
  '@codemirror/commands',
  '@codemirror/language',
  '@codemirror/lint',
  '@codemirror/search',
  '@codemirror/state',
  '@codemirror/view',
  '@lezer/common',
  '@lezer/highlight',
  '@lezer/lr',
  ...builtinModules,
]

const content: string = `/*
THIS IS A GENERATED/BUNDLED FILE BY VITE
Please visit the github repository of this plugin for the source file:
https://github.com/idlist/flakepiles
*/`

const files = ['main.js', 'styles.css', 'manifest.json']

const copyTargets = () => {
  const targets: Target[] = []

  for (const file of files) {
    targets.push({ src: file, dest: 'dist' })
  }

  return targets
}

export default defineConfig(({ mode }) => {
  const prod = mode == 'production'

  const define: Record<string, string> = {}
  if (prod) {
    define['process.env.NODE_ENV'] = '"production"'
  }

  return {
    plugins: [
      vue(),
      banner(content),
      copy({ targets: prod ? copyTargets() : [] }),
    ],
    define,
    resolve: {
      alias: {
        '@': fileURLToPath(new URL('./src', import.meta.url)),
      },
    },
    build: {
      target: 'es2018',
      outDir: '.',
      emptyOutDir: false,
      sourcemap: prod ? false : 'inline',
      rollupOptions: {
        external,
      },
      lib: {
        entry: 'src/main.ts',
        fileName: () => 'main.js',
        formats: ['cjs'],
        cssFileName: 'styles',
      },
      minify: prod,
    },
  }
})
